package com.category_tree_bot.command;

import java.io.File;

/**
 * Интерфейс обработчика команд Telegram-бота.
 *
 * <p>Каждый обработчик реализует одну конкретную команду и определяет логику её обработки.
 * Интерфейс поддерживает два варианта обработки:
 * <ul>
 *     <li>Обработка текстовых аргументов команды</li>
 *     <li>Обработка команды с загрузкой файла (опционально)</li>
 * </ul>
 * </p>
 *
 * <p>Примеры поддерживаемых команд:
 * <ul>
 *     <li><code>/addElement</code></li>
 *     <li><code>/viewTree</code></li>
 *     <li><code>/upload</code> — с загрузкой Excel-файла</li>
 * </ul>
 * </p>
 *
 * @author Dinara
 * @see com.category_tree_bot.bot.CategoryTreeBot
 */
public interface CommandHandler {

    /**
     * Возвращает имя Telegram-команды, которую обрабатывает данный обработчик.
     *
     * @return строка с названием команды, например "/upload" или "/addElement"
     */
    String getCommand();

    /**
     * Основной метод обработки команды, полученной от пользователя в виде текста.
     *
     * @param args   массив аргументов, переданных пользователем (введённые слова после команды)
     * @param chatId идентификатор Telegram-чата, откуда пришла команда
     * @return строка-ответ для отображения пользователю
     */
    String handle(String[] args, Long chatId);

    /**
     * Метод по умолчанию для обработки команды, связанной с загрузкой файла.
     * <p>По умолчанию возвращает сообщение о том, что команда не поддерживает файлы.
     * Если команда поддерживает работу с файлами (например, Excel-файлы), метод должен быть переопределён.</p>
     *
     * @param args   массив аргументов команды
     * @param chatId идентификатор чата
     * @param file   файл, загруженный пользователем
     * @return строка-ответ бота
     */
    default String handle(String[] args, Long chatId, File file) {
        return "Эта команда не поддерживает загрузку файла.";
    }
}
